package api

import (
	"fmt"
	"net/url"

	"github.com/goccy/go-json"

	"github.com/lb-selfbot/go-jester"
	"github.com/lb-selfbot/selfbot/internal/http"
)

const lbAPIBaseURL = "https://api.lightning-bot.com/api/v3"

// LBCreds are the credentials for the LightningBot API.
type LBCreds struct {
	Username string
	Password string
}

// Auth authenticates with the LightningBot API.
func LBAuth(creds LBCreds) (*jester.Data, error) {
	resp, err := http.DefaultClient().Post(lbAPIBaseURL+"/auth/auth", map[string]any{
		"username":    creds.Username,
		"password":    creds.Password,
		"client_type": "ui",
	})
	if err != nil {
		return nil, err
	}

	return resp.Json(), nil
}

// LBCreatePaste creates a paste on LightningBot.
func LBCreatePaste(text string) (string, error) {
	resp, err := http.DefaultClient().Post("https://paste.lightning-bot.com/documents", []byte(text))
	if err != nil {
		return "", err
	}

	return "https://paste.lightning-bot.com/%s" + resp.Json().Get("key").MustString(), nil
}

// LBCreateMeme creates a meme using the LightningBot API.
func LBCreateMeme(creds LBCreds, templateID, text0, text1 string) (string, error) {
	resp, err := http.DefaultClient().Post(lbAPIBaseURL+"/selfbot/memegen", map[string]any{
		"username":    creds.Username,
		"password":    creds.Password,
		"template_id": templateID,
		"text0":       text0,
		"text1":       text1,
	})
	if err != nil {
		return "An error has occurred: " + err.Error(), err
	}

	data := resp.Json()

	imageURL := data.Get("url").MustString()
	if imageURL == "" {
		return "An error has occurred: " + data.Get("error").MustString(), fmt.Errorf("empty response")
	}

	return imageURL, nil
}

// LBSearch performs a search using the LightningBot API.
func LBSearch(creds LBCreds, query string) (*jester.Data, error) {
	url := fmt.Sprintf(lbAPIBaseURL+"/misc/search?query=%s", url.QueryEscape(query))

	resp, err := http.DefaultClient().Get(url)
	if err != nil {
		return nil, err
	}

	return resp.Json().Get("results"), nil
}

// LBOCR performs OCR on an image using the LightningBot API.
func LBOCR(creds LBCreds, imageURL string) (string, error) {
	data := map[string]string{
		"username": creds.Username,
		"password": creds.Password,
		"image":    imageURL,
	}

	resp, err := http.DefaultClient().Post(lbAPIBaseURL+"/selfbot/ocr", data)
	if err != nil {
		return "", err
	}

	return resp.Json().Get("text").String()
}

// LBGenImageKey generates an image key using the LightningBot API.
func LBGenImageKey(imageURL string) string {
	resp, err := http.DefaultClient().Post(
		lbAPIBaseURL+"/selfbot/gen-image-key",
		map[string]any{"image_url": imageURL},
	)
	if err != nil {
		return "Error generating image key: " + err.Error()
	}

	return resp.Json().Get("image_key").MustString()
}

// LBObfuscate obfuscates code using the LightningBot API.
func LBObfuscate(lang, code string) string {
	resp, err := http.DefaultClient().Post(
		lbAPIBaseURL+"/selfbot/obfuscate",
		map[string]any{"lang": lang, "code": code},
	)
	if err != nil {
		return "An error has occurred: " + err.Error()
	}

	return resp.Json().Get("code").MustString("An error has occurred.")
}

// CreditCard represents a credit card generated by the LightningBot API.
type CreditCard struct {
	Number        string `json:"number"`
	CVV           string `json:"cvv"`
	ExpiryDate    string `json:"expiry_date"`
	Visualisation string `json:"visualisation"`
}

// LBGenerateCC generates a credit card using the LightningBot API.
func LBGenerateCC(ccType, name string) (cc *CreditCard, err error) {
	url := fmt.Sprintf(lbAPIBaseURL+"/misc/ccgen?type=%s&name=%s", ccType, name)
	resp, err := http.DefaultClient().Get(url)
	if err != nil {
		return nil, err
	}

	if err = json.NewDecoder(resp.Body).Decode(&cc); err != nil {
		return nil, err
	}

	return cc, nil
}

// URLEmbed represents a URL embed.
type URLEmbed struct {
	Title        string
	Description  string
	URL          string
	Color        string
	Image        string
	Large        bool
	Video        string
	ProviderName string
	ProviderURL  string
	AuthorName   string
	AuthorURL    string
}

// LBCreateURLEmbed creates a URL embed using the LightningBot API.
func LBCreateURLEmbed(embed URLEmbed) (string, error) {
	const embedURL = "https://embed.lightning-bot.com/api/embed"

	values := url.Values{
		"title":         {embed.Title},
		"description":   {embed.Description},
		"url":           {embed.URL},
		"color":         {embed.Color},
		"image":         {embed.Image},
		"large":         {fmt.Sprintf("%t", embed.Large)},
		"video":         {embed.Video},
		"provider_name": {embed.ProviderName},
		"provider_url":  {embed.ProviderURL},
		"author_name":   {embed.AuthorName},
		"author_url":    {embed.AuthorURL},
	}

	resp, err := http.DefaultClient().Post(embedURL+"?"+values.Encode(), nil)
	if err != nil {
		return "", err
	}

	return embedURL + "?key=" + string(resp.MustGetBody()), nil
}

// LBGPTCustom generates a response using the LightningBot API.
func LBGPTCustom(creds LBCreds, messages []any, modelSlice ...string) (string, error) {
	model := "gpt-3.5-turbo"
	if len(modelSlice) > 0 {
		model = modelSlice[0]
	}

	resp, err := http.DefaultClient().Post("https://api.lightning-bot.com/api/v3/selfbot/gpt", map[string]any{
		"username": creds.Username,
		"password": creds.Password,
		"model":    model,
		"messages": messages,
	})
	if err != nil {
		return "An error has occurred: " + err.Error(), err
	}

	data := resp.Json()
	content := data.Get("response").MustString()
	if content == "" {
		data := fmt.Sprint(data.Interface())
		return "An error has occurred: " + data, fmt.Errorf("empty response: %s", data)
	}

	return content, nil
}

// LBGPT generates a response using the LightningBot API.
func LBGPT(creds LBCreds, system, prompt string) (string, error) {
	messages := []any{}

	if system != "" {
		messages = append(messages, map[string]any{"role": "system", "content": system})
	}

	if prompt != "" {
		messages = append(messages, map[string]any{"role": "user", "content": prompt})
	}

	return LBGPTCustom(creds, messages)
}
