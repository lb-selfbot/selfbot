func ConvertVolume(from string, to string, val float64) (float64, error) {
	if _, ok := volumeConverters[from]; !ok {
		return 0, ErrUnknownUnit
	}
	if _, ok := volumeConverters[from][to]; !ok {
		return 0, ErrUnknownUnit
	}
	return volumeConverters[from][to](val), nil
}
